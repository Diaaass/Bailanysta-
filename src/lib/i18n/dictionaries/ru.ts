/**
 * Widens the literal types `as const` produces, so every locale has to provide
 * the same keys but is free to provide different words. Without this the other
 * dictionaries would have to repeat the Russian strings verbatim.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : { [K in keyof T]: Widen<T[K]> };

export type Dictionary = Widen<typeof ru>;
